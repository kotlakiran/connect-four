import java.io.File
import java.util.Properties

val signingPropertiesFile = File(
    System.getenv("KOTLAKIRAN_KEYSTORE_PROPERTIES")
        ?: rootProject.file("keystore.properties").absolutePath
)
val signingProperties = Properties().apply {
    if (signingPropertiesFile.isFile) {
        signingPropertiesFile.inputStream().use { load(it) }
    }
}
val releaseStoreFile = signingProperties.getProperty("storeFile")?.let { rootProject.file(it) }
val releaseStorePassword = signingProperties.getProperty("storePassword")
val releaseKeyAlias = signingProperties.getProperty("keyAlias")
val releaseKeyPassword = signingProperties.getProperty("keyPassword")
val hasReleaseSigning = releaseStoreFile != null &&
    releaseStorePassword != null &&
    releaseKeyAlias != null &&
    releaseKeyPassword != null

